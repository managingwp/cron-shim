#!/usr/bin/env bash
# =============================================================================
# control.sh — Generic Docker stack control (auto-detecting)
#
# Usage:
#   ./control.sh create [dev|prod]             first-time setup: .env, secrets, start stack
#   ./control.sh setup [--force] [dev|prod]    create/refresh .env, start stack
#   ./control.sh start                         start the stack
#   ./control.sh stop                          stop and remove containers
#   ./control.sh restart                       restart containers (no rebuild)
#   ./control.sh rebuild                       git pull + rebuild images + recreate
#   ./control.sh status                        show container + version status
#   ./control.sh logs [service]                tail app log (default) or docker logs (service)
#   ./control.sh tunnel quick                  expose app via trycloudflare (no account)
#   ./control.sh tunnel setup                  one-time named tunnel provisioning via API
#   ./control.sh tunnel named                  run provisioned named tunnel
#   ./control.sh tunnel url                    print current remote URL
#   ./control.sh tunnel status                 show tunnel process state
#   ./control.sh tunnel stop                   stop project's cloudflared
#   ./control.sh reset [--yes]                 DESTRUCTIVE wipe + fresh setup
#   ./control.sh help                          show this help
#
# No configuration file needed — this script inspects the repo and detects:
#   * framework   (laravel when artisan+composer.json exist, node for any
#                  package.json, otherwise generic)
#   * compose     which docker-compose files exist (dev/prod/override)
#   * main service (docker compose config --services, preferring a name that
#                  matches the repo, then app/web, then the first service)
#   * secrets     empty *_KEY / *_SECRET / *_PASSWORD / *_TOKEN / APP_KEY
#                  entries in .env(.example) are generated during setup
#   * version     APP_VERSION/GIT_SHA build args are injected only when the
#                  Dockerfile / compose files actually use them
#   * reset scope SQLite files and gitignored data dirs that exist on disk
#
# Generated by the docker-control-sh skill. Repo-specific hooks such as admin
# password resets were intentionally removed; re-add them per project if needed.
# =============================================================================

set -euo pipefail

PROJECT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$PROJECT_DIR"

# ---------------------------------------------------------------------------
# -- Helpers ---------------------------------------------------------------
# ---------------------------------------------------------------------------

log()    { printf '\033[1;36m==> %s\033[0m\n' "$*"; }
warn()   { printf '\033[1;33m!!  %s\033[0m\n' "$*"; }
die()    { printf '\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------------------
# -- Detection -------------------------------------------------------------
# ---------------------------------------------------------------------------

FRAMEWORK="generic"
MAIN_SERVICE=""
COMPOSE_FILES="docker-compose.yml"

detect_framework() {
    if [ -f artisan ] && [ -f composer.json ]; then
        FRAMEWORK="laravel"
    elif [ -f package.json ]; then
        FRAMEWORK="node"
    else
        FRAMEWORK="generic"
    fi
}

detect_main_service() {
    local services names preferred
    if ! services="$(docker compose config --services 2>/dev/null)"; then
        MAIN_SERVICE="app"
        return
    fi
    [ -z "$services" ] && { MAIN_SERVICE="app"; return; }
    names="$(basename "$PROJECT_DIR")
app
web
server
www"

    preferred="$(printf '%s\n' "$names" | while read -r name; do
        printf '%s\n' "$services" | grep -qx "$name" && { printf '%s' "$name"; break; }
    done)" || true
    if [ -n "$preferred" ]; then
        MAIN_SERVICE="$preferred"
    else
        MAIN_SERVICE="$(printf '%s\n' "$services" | head -1)"
    fi
}

# Collect the compose files that actually exist, preferring explicit overrides.
detect_compose_files() {
    local files="" candidate
    for candidate in docker-compose.yml docker-compose.prod.yml docker-compose.override.yml compose.yaml compose.yml; do
        if [ -f "$candidate" ]; then
            [ -n "$files" ] && files="$files:"
            files="$files$candidate"
        fi
    done
    if [ -n "$files" ]; then
        COMPOSE_FILES="$files"
    fi
    return 0
}

# Does the Dockerfile / compose setup consume APP_VERSION or GIT_SHA?
uses_version_args() {
    grep -qsE 'APP_VERSION|GIT_SHA' Dockerfile Dockerfile.* 2>/dev/null ||
        grep -qsE '\$\{?(APP_VERSION|GIT_SHA)\}?' docker-compose*.yml compose.*.y?ml 2>/dev/null
}

# ---------------------------------------------------------------------------
# -- Env helpers ------------------------------------------------------------
# ---------------------------------------------------------------------------

ENV_FILE=".env"
HAS_ENV_EXAMPLE=0
[ -f .env.example ] && HAS_ENV_EXAMPLE=1

get_env() {
    grep -E "^${1}=" "$ENV_FILE" 2>/dev/null | tail -1 | cut -d= -f2- || true
}

set_env() {
    local key="$1" value="$2"
    if grep -qE "^${key}=" "$ENV_FILE"; then
        sed -i "s|^${key}=.*|${key}=${value}|" "$ENV_FILE"
    else
        printf '\n%s=%s\n' "$key" "$value" >> "$ENV_FILE"
    fi
}

unset_env() {
    sed -i "/^${1}=/d" "$ENV_FILE"
}

# Does the key exist in .env or .env.example?
has_key() {
    if grep -qE "^${1}=" "$ENV_FILE" 2>/dev/null; then
        return 0
    fi
    [ -f .env.example ] && grep -qE "^${1}=" .env.example 2>/dev/null
}

generate_secret() {
    if command -v openssl >/dev/null 2>&1; then
        openssl rand -hex 24
    else
        node -e "console.log(require('crypto').randomBytes(24).toString('hex'))"
    fi
}

# Keys from a file that are set to an empty value AND look like secrets.
empty_secret_keys() {
    local file="$1"
    [ -f "$file" ] || return 0
    grep -E '^[A-Za-z_][A-Za-z0-9_]*=$' "$file" | cut -d= -f1 |
        grep -E '(_KEY|_SECRET|_PASSWORD|_TOKEN|APP_KEY|SECRET)$' || true
}

# Fill every empty secret-looking key in .env with a generated value.
fill_secrets() {
    local key generated any=0
    for key in $(empty_secret_keys "$ENV_FILE"); do
        generated="$(generate_secret)"
        set_env "$key" "$generated"
        log "Generated ${key}"
        any=1
    done
    if [ "$any" -eq 1 ]; then
        log "Secrets written to ${ENV_FILE}."
    fi
    return 0
}

# Generate APP_KEY for Laravel via the running stack (like script.1) or a
# one-off run when the app container isn't up yet.
ensure_app_key() {
    [ "$FRAMEWORK" != "laravel" ] && return 0
    if grep -qE '^APP_KEY=.+' "$ENV_FILE" 2>/dev/null; then
        return 0
    fi
    log "Generating APP_KEY (Laravel)..."
    if [ "$(get_env APP_ENV)" = "production" ]; then
        docker compose run --rm --no-deps --entrypoint php \
            -v "$PROJECT_DIR/.env:/var/www/html/.env" \
            "$MAIN_SERVICE" artisan key:generate --force --no-interaction 2>/dev/null \
        || warn "Could not generate APP_KEY in a one-off container — the app entrypoint will do it on first boot."
    else
        docker compose exec -T "$MAIN_SERVICE" php artisan key:generate --force --no-interaction 2>/dev/null \
        || warn "App container not running — APP_KEY will be generated on first boot."
    fi
}

ensure_env_file() {
    if [ -f "$ENV_FILE" ]; then
        return
    fi
    if [ "$HAS_ENV_EXAMPLE" -eq 1 ]; then
        cp .env.example "$ENV_FILE"
        log "Created .env from .env.example"
        fill_secrets
    else
        die "No .env found and no .env.example to copy from. Run 'setup' in an interactive terminal to create one."
    fi
}

# ---------------------------------------------------------------------------
# -- Stack helpers ----------------------------------------------------------
# ---------------------------------------------------------------------------

require_docker() {
    if ! command -v docker >/dev/null 2>&1; then
        die "Docker is not installed or not in PATH."
    fi
    if ! docker compose version >/dev/null 2>&1; then
        die "Docker Compose (v2, 'docker compose') is not available."
    fi
}

# Ask a yes/no question; default "no".
confirm() {
    printf "%s [y/N] " "$1"
    read -r answer || true
    case "$answer" in
        y|Y|yes|YES) return 0 ;;
        *) return 1 ;;
    esac
}

# Wait until the main service is usable. Framework-aware: Laravel is ready
# once `php artisan` works (vendor present). Node/generic fall back to the
# container being up.
wait_ready() {
    local i
    log "Waiting for the ${MAIN_SERVICE} container..."
    for i in $(seq 1 300); do
        if [ "$FRAMEWORK" = "laravel" ]; then
            if docker compose exec -T "$MAIN_SERVICE" php artisan --version >/dev/null 2>&1; then
                log "App container is ready."
                return 0
            fi
        else
            if docker compose ps --services 2>/dev/null | grep -qx "$MAIN_SERVICE" &&
               docker compose ps "$MAIN_SERVICE" 2>/dev/null | grep -q "Up"; then
                log "App container is ready."
                return 0
            fi
        fi
        sleep 1
    done
    warn "App container not ready after 300s — check './control.sh logs ${MAIN_SERVICE}'."
}

# ---------------------------------------------------------------------------
# -- setup -----------------------------------------------------------------
# ---------------------------------------------------------------------------

cmd_setup() {
    local force=0 mode="dev"
    case "${1:-}" in
        --force) force=1 ;;
        dev|prod) mode="$1" ;;
        "") ;;
        *) die "Unknown setup option '${1:-}' (expected --force, dev, prod)" ;;
    esac
    case "${2:-}" in
        dev|prod) mode="$2" ;;
        --force)
            if [ "$force" -eq 0 ]; then
                force=1
            else
                die "Duplicate --force flag"
            fi
            ;;
        "") ;;
        *) die "Unknown setup option '${2:-}' (expected --force, dev, prod)" ;;
    esac

    if [ -f "$ENV_FILE" ] && [ "$force" -eq 1 ]; then
        warn "Overwriting existing .env (backing up to .env.bak)..."
        cp "$ENV_FILE" .env.bak
    fi

    ensure_env_file
    fill_secrets

    # prod only behaves specially when prod/override compose files exist
    if [ "$mode" = "prod" ]; then
        if [ -f docker-compose.prod.yml ] || [ -f docker-compose.override.yml ]; then
            has_key APP_ENV && set_env APP_ENV "production"
            set_env COMPOSE_FILE "$COMPOSE_FILES"
            log "Production mode: COMPOSE_FILE=$COMPOSE_FILES"
            if grep -qE '^APP_DEBUG=true' "$ENV_FILE" 2>/dev/null; then
                warn "APP_DEBUG=true is set — consider false in production."
            fi
        else
            warn "No docker-compose.prod.yml / docker-compose.override.yml found — treating prod like dev."
            has_key APP_ENV && set_env APP_ENV "local"
            unset_env COMPOSE_FILE
        fi
    else
        has_key APP_ENV && set_env APP_ENV "local"
        unset_env COMPOSE_FILE
        if [ "$FRAMEWORK" = "laravel" ] && ! grep -qE '^APP_PORT=' "$ENV_FILE" 2>/dev/null; then
            set_env APP_PORT 8080
        fi
    fi

    require_docker
    detect_main_service
    docker compose config --quiet || die "docker compose config failed — check your compose files."
    docker compose up -d
    wait_ready
    ensure_app_key

    local url port
    port="$(get_env APP_PORT)"
    url="$(get_env APP_BASE_URL)"
    if [ -n "$port" ]; then
        log "Done. Stack available at http://localhost:${port}"
    elif [ -n "$url" ]; then
        log "Done. Stack available at ${url}"
    else
        log "Done."
    fi
    write_port_file
}

# ---------------------------------------------------------------------------
# -- start / stop / restart --------------------------------------------------
# ---------------------------------------------------------------------------

cmd_start() {
    require_docker
    ensure_env_file
    detect_main_service
    docker compose up -d
    wait_ready
    ensure_app_key
    write_port_file
}

cmd_stop() {
    require_docker
    docker compose --profile tunnel down
}

cmd_restart() {
    require_docker
    docker compose restart
}

# ---------------------------------------------------------------------------
# -- rebuild ----------------------------------------------------------------
# ---------------------------------------------------------------------------

cmd_rebuild() {
    require_docker
    detect_main_service

    # Pull the latest code first (skips gracefully when there's no remote or
    # the repo is on a detached HEAD).
    if git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
        log "Pulling latest code (git pull --ff-only)..."
        git pull --ff-only 2>&1 || warn "git pull failed — continuing with current code."
    fi

    # Flag silent drift when a tracked example compose file diverges from the
    # (possibly gitignored) real one.
    if [ -f docker-compose.yml ] && [ -f docker-compose.yml.example ]; then
        if ! diff -q docker-compose.yml docker-compose.yml.example >/dev/null 2>&1; then
            warn "docker-compose.yml differs from docker-compose.yml.example (gitignored file drifts silently):"
            diff docker-compose.yml docker-compose.yml.example || true
            warn "Review the diff before continuing."
        fi
    fi

    # Bake the git version + commit into the image when the image consumes them.
    local version_args=""
    if uses_version_args; then
        local app_version git_sha
        app_version="$(git describe --tags --always --dirty 2>/dev/null || echo dev)"
        app_version="${app_version#v}"
        git_sha="$(git rev-parse --short HEAD 2>/dev/null || echo unknown)"
        log "Rebuilding (v${app_version} @ ${git_sha})..."
        version_args="--build-arg APP_VERSION=$app_version --build-arg GIT_SHA=$git_sha"
    else
        log "Rebuilding images..."
    fi

    docker compose down
    docker compose build --pull $version_args
    docker compose up -d --force-recreate
    wait_ready

    # A rebuild can complete while a container crash-loops; surface it.
    sleep 5
    if docker compose ps 2>/dev/null | grep -q "Restarting"; then
        warn "=== One or more containers are crash-looping:"
        docker compose ps | grep "Restarting" || true
        warn "Check the failing service logs: ./control.sh logs <service>"
    fi
}

# ---------------------------------------------------------------------------
# -- status / logs -----------------------------------------------------------
# ---------------------------------------------------------------------------

cmd_status() {
    require_docker
    log "Container status:"
    docker compose ps

    if docker compose ps --services 2>/dev/null | grep -qx "$MAIN_SERVICE" &&
       docker compose ps "$MAIN_SERVICE" 2>/dev/null | grep -q "Up"; then
        local git_version env_version
        git_version="$(git describe --tags --always --dirty 2>/dev/null || echo dev)"
        env_version="$(get_env APP_VERSION)" || env_version=""
        log "Running version: ${env_version:-$git_version}"
    fi

    local port_file=".port"
    if [ -f "$port_file" ]; then
        log "App port file: $(cat "$port_file")"
    fi
}

write_port_file() {
    local port
    port="$(get_env APP_PORT)"
    if [ -n "$port" ]; then
        printf '%s' "$port" > .port
        log "Wrote app port to .port (${port})"
    fi
}

cmd_logs() {
    local service="${1:-}"
    require_docker
    if [ -n "$service" ]; then
        # Explicit service: tail that container's docker logs.
        docker compose logs -f --tail=100 "$service"
    else
        # Default: tail the Laravel app log file (per project plan), not docker logs.
        if [ "$FRAMEWORK" = "laravel" ]; then
            if docker compose ps --services 2>/dev/null | grep -qx "$MAIN_SERVICE" &&
               docker compose ps "$MAIN_SERVICE" 2>/dev/null | grep -q "Up"; then
                docker compose exec -T "$MAIN_SERVICE" sh -c "touch storage/logs/app.log; tail -f storage/logs/app.log"
            else
                log "App container is not running. Use 'docker' logs? Start it first: ./control.sh start"
            fi
        else
            docker compose logs -f --tail=100
        fi
    fi
}

# ---------------------------------------------------------------------------
# -- reset ------------------------------------------------------------------
# ---------------------------------------------------------------------------

cmd_reset() {
    local force=0
    [ "${1:-}" = "--yes" ] && force=1

    require_docker
    ensure_env_file

    # Find obvious sqlite files shallow-diving, ignoring .git/vendor/node_modules.
    local sqlite_files
    sqlite_files="$(find . -maxdepth 3 -name '*.sqlite*' \
        -not -path './.git/*' -not -path './vendor/*' -not -path './node_modules/*' 2>/dev/null)" || true

    # Gitignored data dirs that exist on disk and are safe candidates to wipe.
    local data_dirs=""
    local dir
    for dir in data database storage tmp runtime; do
        if [ -d "$dir" ] && git check-ignore -q "$dir" 2>/dev/null; then
            data_dirs="$data_dirs $dir"
        fi
    done

    warn ""
    warn "============================================================"
    warn " DESTRUCTIVE — this will DELETE:"
    warn "   • All containers and named volumes  (docker compose down -v)"
    [ -n "$sqlite_files" ] && warn "   • SQLite databases:${sqlite_files//$'\n'/ }"
    [ -n "$data_dirs" ] && warn "   • Gitignored data dirs:$data_dirs"
    if [ "$HAS_ENV_EXAMPLE" -eq 1 ]; then
        warn "   • .env (re-created fresh from .env.example)"
    fi
    warn ""
    warn " This CANNOT BE UNDONE."
    warn "============================================================"
    warn ""
    if [ "$force" -ne 1 ]; then
        confirm "Are you sure you want to wipe the stack?" || { warn "Aborted."; exit 0; }
    fi

    docker compose --profile tunnel down -v

    # SQLite files may be root-owned from container runs; fall back to a root
    # alpine container when a plain rm fails.
    local f
    for f in $sqlite_files; do
        if ! rm -f "$f" 2>/dev/null; then
            docker run --rm -v "$PROJECT_DIR:/app" alpine:latest \
                sh -c "rm -f \"/app/${f#./}\"" >/dev/null 2>&1 || true
        fi
    done

    for dir in $data_dirs; do
        if ! rm -rf "$dir" 2>/dev/null; then
            docker run --rm -v "$PROJECT_DIR:/app" alpine:latest \
                sh -c "rm -rf \"/app/$dir/*\"" >/dev/null 2>&1 || true
            rm -rf "$dir" 2>/dev/null || true
        fi
    done

    log "Stack wiped. Re-running setup..."
    cmd_setup --force
    log "Done. Run './control.sh start' if the stack is not already running."
}

# ---------------------------------------------------------------------------
# -- Tunnel helpers ---------------------------------------------------------
# ---------------------------------------------------------------------------

TUNNEL_PID_FILE=".tunnel.pid"
TUNNEL_URL_FILE=".tunnel-url"

tunnel_is_running() {
    if [ ! -f "$TUNNEL_PID_FILE" ]; then
        return 1
    fi
    local pid
    pid="$(cat "$TUNNEL_PID_FILE" 2>/dev/null)" || return 1
    if kill -0 "$pid" 2>/dev/null; then
        return 0
    fi
    rm -f "$TUNNEL_PID_FILE"
    return 1
}

tunnel_require_port() {
    get_env APP_PORT >/dev/null 2>&1 || die "APP_PORT not set in .env — run './control.sh setup' first."
}

tunnel_stop_if_running() {
    if tunnel_is_running; then
        log "Stopping running tunnel (PID $(cat "$TUNNEL_PID_FILE"))..."
        kill "$(cat "$TUNNEL_PID_FILE")" 2>/dev/null || true
        rm -f "$TUNNEL_PID_FILE" "$TUNNEL_URL_FILE"
    fi
}

tunnel_save_url() {
    local logfile="$1"
    # poll the cloudflared log for the trycloudflare URL (up to 15s)
    local i url
    for i in $(seq 1 15); do
        url="$(grep -oE 'https://[a-z0-9-]+\.trycloudflare\.com' "$logfile" 2>/dev/null | head -1)"
        if [ -n "$url" ]; then
            printf '%s' "$url" > "$TUNNEL_URL_FILE"
            printf '%s' "$url"
            return 0
        fi
        sleep 1
    done
    return 1
}

# ---------------------------------------------------------------------------
# -- cmd_tunnel_quick --------------------------------------------------------
# ---------------------------------------------------------------------------

cmd_tunnel_quick() {
    tunnel_require_port
    tunnel_stop_if_running

    local port logfile
    port="$(get_env APP_PORT)"
    logfile="${TUNNEL_PID_FILE}.log"

    log "Starting quick tunnel on port ${port}..."

    cloudflared tunnel --url "http://localhost:${port}" \
        --no-autoupdate \
        --metrics "localhost:0" \
        --logfile "$logfile" &
    local pid=$!
    printf '%s' "$pid" > "$TUNNEL_PID_FILE"

    local url
    url="$(tunnel_save_url "$logfile")" || {
        warn "Could not determine tunnel URL after 15s — check ${logfile}"
        return 1
    }

    log "Quick tunnel ready: ${url}"
}

# ---------------------------------------------------------------------------
# -- cmd_tunnel_setup --------------------------------------------------------
# ---------------------------------------------------------------------------

cmd_tunnel_setup() {
    tunnel_require_port

    local token account_id zone_id hostname tunnel_name port origin
    token="${CF_API_TOKEN:-$(get_env CF_API_TOKEN)}"
    account_id="${CF_ACCOUNT_ID:-$(get_env CF_ACCOUNT_ID)}"
    zone_id="${CF_ZONE_ID:-$(get_env CF_ZONE_ID)}"
    hostname="${CF_TUNNEL_HOSTNAME:-$(get_env CF_TUNNEL_HOSTNAME)}"
    tunnel_name="${CF_TUNNEL_NAME:-$(get_env CF_TUNNEL_NAME)}"
    port="$(get_env APP_PORT)"
    origin="${CF_TUNNEL_ORIGIN:-$(get_env CF_TUNNEL_ORIGIN)}"

    # Defaults
    : "${tunnel_name:=$(basename "$PROJECT_DIR")}"
    : "${origin:=http://localhost:${port}}"

    if [ -z "$hostname" ]; then
        die "CF_TUNNEL_HOSTNAME is required. Set it in .env and retry."
    fi
    if [ -z "$token" ] || [ -z "$account_id" ] || [ -z "$zone_id" ]; then
        die "Missing one or more of: CF_API_TOKEN, CF_ACCOUNT_ID, CF_ZONE_ID. Add them to .env and retry."
    fi

    log "Verifying API token..."
    local verify
    verify="$(curl -sf -H "Authorization: Bearer ${token}" "https://api.cloudflare.com/client/v4/user/tokens/verify")" || {
        die "Token verification failed — check CF_API_TOKEN."
    }
    log "Token verified."

    # Check if tunnel already exists
    local existing_tunnel tunnel_id tunnel_run_token
    existing_tunnel="$(curl -sf -H "Authorization: Bearer ${token}" \
        "https://api.cloudflare.com/client/v4/accounts/${account_id}/cfd_tunnel?name=${tunnel_name}" 2>/dev/null)"

    if echo "$existing_tunnel" | grep -q '"id"'; then
        tunnel_id="$(echo "$existing_tunnel" | grep -oP '"id":"\K[^"]+' | head -1)"
        log "Tunnel '${tunnel_name}' already exists (id: ${tunnel_id}). Reusing."
        # Get its token (API wraps the token string in result)
        tunnel_run_token="$(curl -sf -H "Authorization: Bearer ${token}" \
            "https://api.cloudflare.com/client/v4/accounts/${account_id}/cfd_tunnel/${tunnel_id}/token" 2>/dev/null | grep -oP '"result":"\K[^"]+')" || {
            die "Could not retrieve tunnel token — check tunnel exists."
        }
    else
        log "Creating tunnel '${tunnel_name}'..."
        local tunnel_secret
        tunnel_secret="$(openssl rand -base64 32 2>/dev/null || node -e "console.log(require('crypto').randomBytes(32).toString('base64'))")"

        local create_result
        create_result="$(curl -sf -X POST -H "Authorization: Bearer ${token}" \
            -H "Content-Type: application/json" \
            "https://api.cloudflare.com/client/v4/accounts/${account_id}/cfd_tunnel" \
            -d "{\"name\":\"${tunnel_name}\",\"config_src\":\"cloudflare\",\"tunnel_secret\":\"${tunnel_secret}\"}")" || {
            die "Tunnel creation failed."
        }

        tunnel_id="$(echo "$create_result" | grep -oP '"id":"\K[^"]+' | head -1)"
        tunnel_run_token="$(echo "$create_result" | grep -oP '"token":"\K[^"]+' | head -1)"
        log "Tunnel created (id: ${tunnel_id})."
    fi

    set_env CF_TUNNEL_ID "$tunnel_id"

    # Write the run token to .env
    set_env TUNNEL_TOKEN "$tunnel_run_token"

    log "Configuring ingress for ${hostname} → ${origin}..."
    curl -sf -X PUT -H "Authorization: Bearer ${token}" \
        -H "Content-Type: application/json" \
        "https://api.cloudflare.com/client/v4/accounts/${account_id}/cfd_tunnel/${tunnel_id}/configurations" \
        -d "{\"config\":{\"ingress\":[{\"hostname\":\"${hostname}\",\"service\":\"${origin}\",\"originRequest\":{}},{\"service\":\"http_status:404\"}]}}" >/dev/null || {
        die "Ingress configuration failed."
    }

    log "Creating DNS record (CNAME ${hostname} → ${tunnel_id}.cfargotunnel.com)..."
    curl -sf -X POST -H "Authorization: Bearer ${token}" \
        -H "Content-Type: application/json" \
        "https://api.cloudflare.com/client/v4/zones/${zone_id}/dns_records" \
        -d "{\"type\":\"CNAME\",\"name\":\"${hostname}\",\"content\":\"${tunnel_id}.cfargotunnel.com\",\"proxied\":true}" >/dev/null || {
        warn "DNS record creation failed — may already exist."
    }

    log "Setup complete. Run './control.sh tunnel named' to start the tunnel."
    log "  Tunnel:  ${tunnel_name}  (${tunnel_id})"
    log "  Hostname: ${hostname}"
}

# ---------------------------------------------------------------------------
# -- cmd_tunnel_named --------------------------------------------------------
# ---------------------------------------------------------------------------

cmd_tunnel_named() {
    require_docker
    tunnel_require_port
    tunnel_stop_if_running

    local run_token hostname
    run_token="$(get_env TUNNEL_TOKEN)"
    hostname="${CF_TUNNEL_HOSTNAME:-$(get_env CF_TUNNEL_HOSTNAME)}"

    if [ -z "$run_token" ]; then
        die "TUNNEL_TOKEN not set in .env. Run './control.sh tunnel setup' first."
    fi
    if [ -z "$hostname" ]; then
        die "CF_TUNNEL_HOSTNAME is required. Set it in .env and retry."
    fi

    log "Starting named tunnel (docker compose service) to ${hostname}..."

    docker compose --profile tunnel up -d cloudflared

    printf '%s' "https://${hostname}" > "$TUNNEL_URL_FILE"

    log "Named tunnel started: https://${hostname}"
}

# ---------------------------------------------------------------------------
# -- cmd_tunnel_url / status / stop ------------------------------------------
# ---------------------------------------------------------------------------

cmd_tunnel_url() {
    if [ -f "$TUNNEL_URL_FILE" ]; then
        echo "$(cat "$TUNNEL_URL_FILE")"
    else
        echo ""
    fi
}

cmd_tunnel_status() {
    local url
    if tunnel_is_running; then
        echo "up"
        url="$(cmd_tunnel_url)"
        if [ -n "$url" ]; then
            echo "url: $url"
        fi
        return 0
    fi
    if command -v docker >/dev/null 2>&1 &&
       docker compose --profile tunnel ps cloudflared 2>/dev/null | grep -q "Up"; then
        echo "up"
        url="$(cmd_tunnel_url)"
        if [ -n "$url" ]; then
            echo "url: $url"
        fi
    else
        echo "stopped"
    fi
}

cmd_tunnel_stop() {
    tunnel_stop_if_running
    if command -v docker >/dev/null 2>&1; then
        docker compose --profile tunnel rm -sf cloudflared >/dev/null 2>&1 || true
    fi
    rm -f "$TUNNEL_URL_FILE"
    log "Tunnel stopped."
}

